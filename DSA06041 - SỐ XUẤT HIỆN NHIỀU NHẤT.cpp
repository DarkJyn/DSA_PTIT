using ll = long long;

#define MOD 1000000007
#define endl "\n"

signed main(){
    cin.tie(nullptr)->sync_with_stdio(false);
    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int a[n];
        map<int,int> mp;
        int maxx = -1;
        for(int i = 0;i < n;++i){
            cin >> a[i];
            mp[a[i]]++;
            if(mp[a[i]] > maxx){
                maxx = a[i];
            }
        }
        if(mp[maxx] > n / 2) cout << maxx;
        else cout <<"NO";
        cout << endl;
    }    
}
